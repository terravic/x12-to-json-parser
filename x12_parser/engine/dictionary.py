def get_segment_name(segment_id: str) -> str:
    """Return friendly name for a segment ID."""
    return SEGMENT_NAMES.get(segment_id.upper(), f"Segment {segment_id}")


def get_element_name(segment_id: str, element_pos: int) -> str:
    """Return friendly name for a segment element position (1-based)."""
    seg_map = SEGMENT_ELEMENT_MAP.get(segment_id.upper(), {})
    return seg_map.get(element_pos, f"element_{element_pos:02d}")


def get_code_description(category: str, code: str) -> Optional[str]:
    """Return human readable description for a code value."""
    cat_map = CODE_DESCRIPTIONS.get(category, {})
    return cat_map.get(str(code).strip())
